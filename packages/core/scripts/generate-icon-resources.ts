import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { MENU_ICON_COLLECTION_SOURCES } from '../src/ui/icon-collections';

/** Freeze installed, lockfile-pinned Iconify data into the JS/compiled distribution. */
export async function generateIconResources(): Promise<void> {
  const require = createRequire(import.meta.url);
  const resources = [];
  const digest = createHash('sha256');
  for (const source of MENU_ICON_COLLECTION_SOURCES) {
    const data = await Bun.file(require.resolve(`${source.packageName}/icons.json`)).json();
    const pkg = await Bun.file(require.resolve(`${source.packageName}/package.json`)).json();
    const info = await Bun.file(require.resolve(`${source.packageName}/info.json`)).json();
    const names = [...Object.keys(data.icons), ...Object.keys(data.aliases ?? {})].sort();
    const raw = JSON.stringify(data);
    digest.update(source.id).update(pkg.version).update(raw);
    resources.push({ metadata: { id: source.id, title: info.name, version: pkg.version, total: names.length,
      license: { title: info.license.title, ...(info.license.url ? { url: info.license.url } : {}) } },
      names, compressed: gzipSync(raw, { level: 9 }).toString('base64') });
  }
  await Bun.write(resolve(import.meta.dir, '../src/ui/icon-resources.ts'),
    `// Generated by scripts/generate-icon-resources.ts. Do not edit.\nexport const ICON_REVISION = ${JSON.stringify(digest.digest('hex'))};\nexport const ICON_RESOURCES = ${JSON.stringify(resources)};\n`);
}
if (import.meta.main) await generateIconResources();
