const UI_MARKERS = '// Auto-generated by scripts/bundle-ui.ts\n// Do not edit manually\n';

function git(root: string, ...args: string[]): void {
  const result = Bun.spawnSync({ cmd: ['git', ...args], cwd: root, stdout: 'pipe', stderr: 'pipe' });
  if (result.exitCode !== 0) throw new Error(new TextDecoder().decode(result.stderr));
}

async function createTarget(asset = UI_MARKERS, source = 'export {};\n'): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'bungee-real-proxy-target-'));
  await mkdir(join(root, 'packages/core/src/ui'), { recursive: true });
  await writeFile(join(root, 'package.json'), '{}\n');
  await writeFile(join(root, 'bun.lock'), '{}\n');
  await writeFile(join(root, 'packages/core/src/main.ts'), source);
  if (asset !== undefined) await writeFile(join(root, 'packages/core/src/ui/assets.ts'), asset);
  git(root, 'init', '-q');
  git(root, 'add', '.');
  git(root, '-c', 'user.name=Bungee Test', '-c', 'user.email=bungee-test@example.invalid', 'commit', '-qm', 'fixture');
  return root;
}

const SCENARIOS_FOR_TEST = [...SCENARIO_NAMES];

function logicalRecords(): PairRecord[] {
  return Array.from({ length: 5 }, (_, logical_block) => SCENARIOS_FOR_TEST.flatMap((scenario) =>
    (['AB', 'BA'] as const).map((leg) => ({
      schema: 'bungee.performance.real-proxy.raw', version: 3, logical_block, repeat: logical_block,
      scenario, scenario_order: SCENARIOS_FOR_TEST, leg,
      order: leg === 'AB' ? ['before', 'after'] : ['after', 'before'],
      run: { argv: [], cwd: '', runner_sha: '', profile_hash: '', config: { before: {}, after: {} } },
      before: { label: 'before', target: {}, valid: true, report: { metric: leg === 'AB' ? 1 : 9 } },
      after: { label: 'after', target: {}, valid: true, report: { metric: leg === 'AB' ? 4 : 1 } },
    } as unknown as PairRecord)),
  )).flat();
}

