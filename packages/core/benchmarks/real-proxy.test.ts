import { describe, expect, test } from 'bun:test';
import { mkdtemp, mkdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { formatBenchmarkError, main, parseArguments, publishConfiguration, validatePreflight, validateTarget } from './real-proxy';
import { startUpstream } from './real-proxy-scenarios';

const UI_MARKERS = '// Auto-generated by scripts/bundle-ui.ts\n// Do not edit manually\n';

function git(root: string, ...args: string[]): void {
  const result = Bun.spawnSync({ cmd: ['git', ...args], cwd: root, stdout: 'pipe', stderr: 'pipe' });
  if (result.exitCode !== 0) throw new Error(new TextDecoder().decode(result.stderr));
}

async function createTarget(asset = UI_MARKERS, source = 'export {};\n'): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'bungee-real-proxy-target-'));
  await mkdir(join(root, 'packages/core/src/ui'), { recursive: true });
  await writeFile(join(root, 'package.json'), '{}\n');
  await writeFile(join(root, 'bun.lock'), '{}\n');
  await writeFile(join(root, 'packages/core/src/main.ts'), source);
  if (asset !== undefined) await writeFile(join(root, 'packages/core/src/ui/assets.ts'), asset);
  git(root, 'init', '-q');
  git(root, 'add', '.');
  git(root, '-c', 'user.name=Bungee Test', '-c', 'user.email=bungee-test@example.invalid', 'commit', '-qm', 'fixture');
  return root;
}

describe('real proxy formal CLI', () => {
  test('accepts only the three absolute target/output options', () => {
    expect(parseArguments(['--before-root=/a', '--after-root', '/b', '--output', '/tmp/result'])).toEqual({
      beforeRoot: '/a', afterRoot: '/b', output: '/tmp/result', help: false,
    });
    expect(() => parseArguments(['--quick'])).toThrow();
    expect(() => parseArguments(['--before-root', 'relative', '--after-root', '/b', '--output', '/tmp/result'])).toThrow();
  });

  test('help is the only argument-free mode', () => {
    expect(parseArguments(['--help']).help).toBe(true);
    expect(() => parseArguments([])).toThrow();
  });

  test('preflight rejects the driver repository as a duplicate target and existing output', async () => {
    const root = resolve(import.meta.dir, '../../..');
    await expect(validatePreflight(root, root, '/tmp/unused-new-result')).rejects.toThrow('distinct');
  });

  test('preflight accepts a generated UI asset stub with valid markers', async () => {
    const root = await createTarget();
    try { await expect(validateTarget(root)).resolves.toMatchObject({ root }); }
    finally { await rm(root, { recursive: true, force: true }); }
  });

  test('preflight rejects a missing generated UI asset', async () => {
    const root = await createTarget();
    await rm(join(root, 'packages/core/src/ui/assets.ts'));
    try { await expect(validateTarget(root)).rejects.toThrow('run full `bun run build`'); }
    finally { await rm(root, { recursive: true, force: true }); }
  });

  test('preflight rejects invalid generated UI asset markers', async () => {
    const root = await createTarget('// Auto-generated by scripts/bundle-ui.ts\n// edited manually\n');
    try { await expect(validateTarget(root)).rejects.toThrow('invalid generation markers'); }
    finally { await rm(root, { recursive: true, force: true }); }
  });

  test('preflight rejects a generated UI asset symlink escaping the target', async () => {
    const root = await createTarget();
    const asset = join(root, 'packages/core/src/ui/assets.ts');
    const outside = join(tmpdir(), `bungee-real-proxy-assets-${Date.now()}.ts`);
    await writeFile(outside, UI_MARKERS);
    await rm(asset);
    await symlink(outside, asset);
    try { await expect(validateTarget(root)).rejects.toThrow('escapes repository'); }
    finally {
      await rm(root, { recursive: true, force: true });
      await rm(outside, { force: true });
    }
  });

  test('configuration polling fails immediately for degraded operations', async () => {
    const server = Bun.serve({ port: 0, fetch: (request) => request.method === 'PUT'
      ? new Response('{}', { status: 202 })
      : Response.json({ operation: { state: 'degraded', error_code: 'runtime_degraded' } }) });
    try {
      await expect(publishConfiguration(server.port!, 1234, '/a', 1, 'b5000000-0000-4000-8000-000000000001', 20))
        .rejects.toThrow('configuration operation degraded: error_code=runtime_degraded');
    } finally { server.stop(true); }
  });

  test('configuration polling timeout includes the latest safe operation evidence', async () => {
    const server = Bun.serve({ port: 0, fetch: (request) => request.method === 'PUT'
      ? new Response('{}', { status: 202 })
      : Response.json({ operation: { state: 'warming', error_code: 'pending', token: 'must-not-leak' } }) });
    try {
      let error: unknown;
      try { await publishConfiguration(server.port!, 1234, '/a', 1, 'b5000000-0000-4000-8000-000000000001', 20); }
      catch (caught) { error = caught; }
      expect(error).toBeInstanceOf(Error);
      expect((error as Error).message).toContain('latest state=warming status=200 error_code=pending');
      expect((error as Error).message).not.toContain('must-not-leak');
    } finally { server.stop(true); }
  });

  test('formal startup failure writes bounded failure evidence without a comparison', async () => {
    const before = await createTarget(UI_MARKERS, 'throw new Error("fixture startup failure");\n');
    const after = await createTarget();
    const outputParent = await mkdtemp(join(tmpdir(), 'bungee-real-proxy-failure-'));
    const output = join(outputParent, 'result');
    try {
      await expect(main(['--before-root', before, '--after-root', after, '--output', output])).rejects.toBeDefined();
      const failure = JSON.parse(await readFile(join(output, 'failure.json'), 'utf8')) as Record<string, any>;
      expect(failure).toMatchObject({
        schema: 'bungee.performance.real-proxy.failure', version: 1, completed_pairs: 0,
        runner: { bun: Bun.version }, error: { name: 'Error' },
      });
      expect(failure.error.message).toContain('before/ordinary');
      expect(failure.error.cause).toBeDefined();
      expect(await Bun.file(join(output, 'comparison.json')).exists()).toBe(false);
    } finally {
      await rm(before, { recursive: true, force: true });
      await rm(after, { recursive: true, force: true });
      await rm(outputParent, { recursive: true, force: true });
    }
  });

  test('benchmark error formatter bounds and redacts nested causes', () => {
    const cause = new Error(`token=secret-value ${'x'.repeat(20_000)}`);
    const error = new Error('outer failure', { cause });
    const formatted = formatBenchmarkError(error) as { readonly cause: { readonly message: string } };
    expect(formatted.cause.message).not.toContain('secret-value');
    expect(formatted.cause.message.length).toBeLessThanOrEqual(16 * 1024);
  });

  test('large-response fixture emits one 4 MiB body, not three UTF-8 expansions', async () => {
    const upstream = await startUpstream();
    try {
      const response = await fetch(`http://127.0.0.1:${upstream.port}/a/bench?scenario=large-response`);
      const body = new Uint8Array(await response.arrayBuffer());
      expect(body.byteLength).toBe(4 * 1024 * 1024);
      expect(body[0]).toBe(0x52);
      expect(upstream.snapshot()).toMatchObject({ requests: 1, bytes: 4 * 1024 * 1024 });
    } finally {
      await upstream.server.stop(true);
    }
  });
});
